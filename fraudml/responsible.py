"""Responsible and explainable AI: global feature importance, per-decision explanations, slice
metrics across customer groups, and a model card."""
from __future__ import annotations

import numpy as np
import pandas as pd
from sklearn.inspection import permutation_importance
from sklearn.metrics import average_precision_score, make_scorer


def global_importance(model, X: pd.DataFrame, y, n_repeats: int = 3, top: int = 10, seed: int = 0) -> dict:
    """Permutation importance: drop in PR-AUC when a feature is shuffled (model-agnostic)."""
    scorer = make_scorer(average_precision_score, response_method="predict_proba")
    r = permutation_importance(model, X, y, scoring=scorer, n_repeats=n_repeats, random_state=seed, n_jobs=-1)
    order = np.argsort(-r.importances_mean)[:top]
    return {X.columns[i]: round(float(r.importances_mean[i]), 4) for i in order}


def local_explanation(model, X: pd.DataFrame, row: int, top: int = 5) -> dict:
    """Why was this transaction flagged? Change in fraud score when each feature is replaced by the
    population median (a simple, model-agnostic counterfactual explanation)."""
    x = X.iloc[[row]]
    base = float(model.predict_proba(x)[0, 1])
    med = X.median()
    deltas = {}
    for c in X.columns:
        x2 = x.copy()
        x2[c] = med[c]
        deltas[c] = base - float(model.predict_proba(x2)[0, 1])
    top_items = sorted(deltas.items(), key=lambda kv: -abs(kv[1]))[:top]
    return {"score": round(base, 4), "top_contributions": {k: round(v, 4) for k, v in top_items}}


def slice_metrics(y, score, groups: pd.Series, threshold: float) -> dict:
    """Recall and false-positive rate per group at one operating threshold. Large gaps in FPR mean
    some customer groups get far more declined or held transactions than others."""
    y, score, groups = np.asarray(y), np.asarray(score), np.asarray(groups)
    out = {}
    for g in np.unique(groups):
        m = groups == g
        flagged = score[m] >= threshold
        pos, neg = y[m] == 1, y[m] == 0
        out[str(g)] = {"n": int(m.sum()), "fraud": int(pos.sum()),
                       "recall": round(float(flagged[pos].mean()), 4) if pos.any() else None,
                       "false_positive_rate": round(float(flagged[neg].mean()), 5) if neg.any() else None}
    fprs = [v["false_positive_rate"] for v in out.values() if v["false_positive_rate"]]
    disparity = round(max(fprs) / min(fprs), 2) if len(fprs) > 1 and min(fprs) > 0 else None
    return {"by_group": out, "fpr_disparity_ratio": disparity}


def model_card(results: dict) -> str:
    c = results["champion_final"]
    lines = [
        "# Model card: transaction fraud detection",
        "",
        "## Intended use",
        "Rank card transactions for analyst review and step-up authentication. Not for automatic account",
        "closure. Decisions on flagged transactions stay with a human reviewer.",
        "",
        "## Data",
        f"Synthetic transactions generated by `fraudml.data` ({results['data']['rows']:,} rows, "
        f"{results['data']['fraud_rate_pct']}% fraud, {results['data']['days']} days, drift from day {results['data']['drift_day']}).",
        "Features use only each customer's past transactions (point-in-time correct).",
        "",
        "## Model",
        f"Champion: {c['version']} ({c['model']}), trained on {c['trained_on']}.",
        "",
        "## Performance (held-out final window)",
        "| Metric | Value |",
        "|---|---|",
    ] + [f"| {k} | {v} |" for k, v in c["metrics"].items() if k not in ("n", "positives")] + [
        "",
        "## Fairness and slices",
        "False-positive rate and recall by customer segment and channel at the 0.5% review budget:",
        "```",
        str(results["responsible_ai"]["slices_segment"]),
        str(results["responsible_ai"]["slices_channel"]),
        "```",
        "",
        "## Explainability",
        f"Top global features (permutation importance): {results['responsible_ai']['global_importance']}",
        "Every alert carries a per-transaction explanation (`fraudml.responsible.local_explanation`).",
        "",
        "## Monitoring and retraining",
        "Feature and score PSI are tracked weekly; retraining triggers on PSI > 0.2, score PSI > 0.1 or a",
        "PR-AUC drop > 0.05 on newly labelled data. A challenger is promoted only if it beats the champion",
        "by at least 0.01 PR-AUC on the most recent labelled window.",
        "",
        "## Limitations",
        "Trained and evaluated on synthetic data; performance on real portfolios must be re-measured.",
        "Recent fraud is under-labelled because chargebacks arrive late.",
    ]
    return "\n".join(lines) + "\n"
